class Worker:
    def __init__(self, db, spool, mode, allowlist, max_streams):
        self.db = db
        self.spool = spool
        self.mode = mode
        self.allowlist = allowlist
        self.max_streams = max_streams
        self.identity = f"{socket.gethostname()}-{uuid.uuid4().hex}"
        self.users = {}
        self.preferences = {}
        self.wake = asyncio.Event()
        self.stopping = asyncio.Event()
        self.refresh_requested = True
        self.jobs_requested = True
        self.realtime_healthy = False
        self.queue_counts = (-1, -1, -1)
        self.disk_pressure = DiskPressure(spool)
        self.disk_sample = None
        self.disk_sample_due = 0
        self.next_storage_stop = 0
        self.storage_draining = None
        self.free_at_last_storage_stop = None
        self.discovery_limit = asyncio.Semaphore(12)
        self.completed = {}
        self.pending_parts = set()

    def eligible(self, username):
        return self.mode != "canary" or username in self.allowlist

    async def discover(self, stream, *, max_wait=8):
        async with self.discovery_limit:
            try:
                details = await asyncio.wait_for(
                    asyncio.to_thread(recorder_core.check_live_details, stream.username, max_wait=max_wait),
                    max_wait + 0.25,
                )
            except asyncio.TimeoutError:
                return "unavailable", None
            room = details.get("room_id")
            if details.get("probe_state") == "live" and room:
                return "live", room
            return ("offline", None) if details.get("probe_state") == "offline" else ("unavailable", None)

    async def source_urls(self, stream, room, budget=10):
        try:
            return ordered_sources(await asyncio.wait_for(
                asyncio.to_thread(recorder_core.get_stream_urls, room, stream.username, max_wait=budget),
                budget + 0.25,
            ))
        except asyncio.TimeoutError:
            return []

    async def status(self, stream, status, owner=None, *, force=False):
        if not force:
            stream.desired_status = status
        async with stream.status_lock:
            sent_recently = stream.status == status and time.monotonic() - stream.status_sent_at < 60
            if stream.desired_status != status or (not force and sent_recently):
                return
            if self.mode == "shadow":
                LOG.info("@%s discovery: %s", stream.username, status)
                stream.status = status
                stream.status_sent_at = time.monotonic()
                return
            try:
                accepted = await asyncio.wait_for(self.db.rpc(
                    "set_stream_state", p_username=stream.username, p_owner=owner,
                    p_status=status, p_is_live=bool(stream.live), p_is_recording=status == "recording",
                ), timeout=2)
                if accepted:
                    stream.status = status
                    stream.status_sent_at = time.monotonic()
            except (aiohttp.ClientError, asyncio.TimeoutError) as error:
                LOG.warning("@%s state update: %s", stream.username, type(error).__name__)

    async def observe(self, stream):
        try:
            if not stream.enabled:
                stream.probe.due = time.monotonic() + 10
                await self.status(stream, "paused")
                signal = "paused"
            else:
                if stream.status is None:
                    await self.status(stream, "probing")
                signal, room = await self.discover(stream)
                if not stream.enabled or stream.removed:
                    return
                stream.probe.observe(signal, time.monotonic())
                if signal == "live":
                    current_room = stream.room
                    stream.live = True
                    stream.room = room
                    now = time.monotonic()
                    if current_room != room:
                        stream.first_live_at = now
                    if current_room != room or stream.waiting_since is None:
                        stream.waiting_since = now
                    if self.mode == "shadow":
                        await self.status(stream, "live")
                else:
                    stream.waiting_since = None
                    if signal == "offline" and stream.probe.confirmed_offline:
                        stream.live = False
                        stream.room = None
                        await self.status(stream, "offline")
                    elif signal == "unavailable":
                        await self.status(stream, "unknown")
                    elif stream.status in ("waiting_slot", "waiting_storage"):
                        await self.status(stream, "live")
            if stream.job:
                self.completed[stream.job["job_key"]] = (stream.job, signal)
                stream.job = None
            if signal != "live":
                stream.add_requested_at = None
        except Exception as error:
            LOG.warning("@%s probe failed (%s)", stream.username, type(error).__name__)
            stream.probe.observe("unavailable", time.monotonic())
        finally:
            stream.observation = None
            self.wake.set()

    async def renew(self, stream, owner, expires, lost):
        while not stream.stop.is_set():
            delay = max(0, min(10, expires - time.monotonic() - 5))
            if await sleep_or_stop(stream.stop, delay):
                return
            remaining = expires - time.monotonic()
            try:
                if remaining <= 1:
                    break
                accepted = await asyncio.wait_for(self.db.rpc(
                    "renew_stream", p_username=stream.username, p_owner=owner, p_ttl_seconds=LEASE_SECONDS,
                ), min(remaining - 0.5, 5))
                if not accepted:
                    break
                expires = time.monotonic() + LEASE_SECONDS - 5
                if stream.desired_status == "recording":
                    await self.status(stream, "recording", owner, force=True)
            except (aiohttp.ClientError, asyncio.TimeoutError):
                if await sleep_or_stop(stream.stop, min(2, max(0, expires - time.monotonic()))):
                    return
        if not stream.stop.is_set():
            lost.set()
            stream.stop.set()

    async def finalize(self, stream, session_id, part):
        try:
            await asyncio.to_thread(
                enqueue_part, self.spool, stream.username, session_id, part, deleted=stream.removed,
            )
        except (OSError, RuntimeError, ValueError, ImportError, subprocess.TimeoutExpired) as error:
            self.pending_parts.add(part)
            LOG.error("@%s retained a local part after enqueue failure (%s)", stream.username, type(error).__name__)
        else:
            self.pending_parts.discard(part)

    async def capture_session(self, stream, owner):
        started = datetime.now(timezone.utc)
        session_id = started.strftime("%Y%m%dT%H%M%SZ_") + uuid.uuid4().hex[:10]
        root = self.spool / "capture" / stream.username / session_id
        room = stream.room
        number = 1
        part_duration = 0.0
        part_target = PART_SECONDS - PART_TAIL_MARGIN
        part = root / f"{number:04d}"
        outage_since = time.monotonic()
        reconnect_checks = 0
        cached_source = None
        try:
            await self.status(stream, "live", owner)
            while not stream.stop.is_set():
                deadline = outage_since + RECONNECT_SECONDS
                if time.monotonic() >= deadline:
                    break

                sources = [cached_source] if cached_source else await self.source_urls(
                    stream, room, min(10, deadline - time.monotonic()),
                )
                process = await begin_capture(
                    sources, part, duration=part_target - part_duration, stop=stream.stop,
                    startup_deadline=min(deadline, time.monotonic() + 18),
                )
                cached_source = None
                if process is not None:
                    reconnect_checks = 0
                    first_frame_at = datetime.now(timezone.utc) - timedelta(
                        seconds=max(0, time.monotonic() - process.first_frame_at),
                    )
                    add_timing = ""
                    if stream.add_requested_at is not None:
                        add_seconds = (first_frame_at - stream.add_requested_at).total_seconds()
                        if add_seconds >= 0:
                            add_timing = f" add_to_first_seconds={add_seconds:.3f}"
                        stream.add_requested_at = None
                    LOG.info(
                        "capture_first_frame username=%s height=%d width=%d first_frame_at=%s source_wait_seconds=%.3f discovery_to_first_seconds=%.3f%s",
                        stream.username, process.resolution[1], process.resolution[0], first_frame_at.isoformat(),
                        max(0, process.first_frame_at - outage_since),
                        max(0, process.first_frame_at - (stream.first_live_at or outage_since)),
                        add_timing,
                    )
                    try:
                        await self.status(stream, "recording", owner)
                        next_sync = time.monotonic() + SEGMENT_SECONDS
                        while (
                            process.process.returncode is None and not stream.stop.is_set()
                            and time.monotonic() - process.last_progress < 15
                        ):
                            if time.monotonic() >= next_sync:
                                await asyncio.to_thread(process.sync_closed_segments)
                                next_sync = time.monotonic() + 10
                            await sleep_or_stop(stream.stop, 0.25)
                    finally:
                        await process.close()
                    # Count previously closed attempts by presentation time so a
                    # reconnect cannot accumulate the reordering at each cutoff.
                    elapsed = min(max(0, process.presentation_seconds()), part_target - part_duration)
                    part_duration += elapsed
                    outage_since = process.last_progress
                    if part_duration >= part_target - 0.10:
                        await self.finalize(stream, session_id, part)
                        number += 1
                        part = root / f"{number:04d}"
                        part_duration = 0
                        cached_source = process.url
                        outage_since = time.monotonic()
                        continue

                if stream.stop.is_set():
                    break
                await self.status(stream, "reconnecting", owner)
                while not stream.stop.is_set():
                    deadline = outage_since + RECONNECT_SECONDS
                    now = time.monotonic()
                    if now >= deadline:
                        return "unknown"
                    try:
                        signal, updated_room = await asyncio.wait_for(
                            self.discover(stream, max_wait=min(8, deadline - now)), deadline - now,
                        )
                    except asyncio.TimeoutError:
                        return "unknown"
                    if signal == "live":
                        reconnect_checks = 0
                        if updated_room != room:
                            stream.room = updated_room
                            stream.first_live_at = time.monotonic()
                            return "live"
                        await sleep_or_stop(stream.stop, min(1, max(0, deadline - time.monotonic())))
                        break
                    reconnect_checks = reconnect_checks + 1 if signal == "offline" else 0
                    if reconnect_checks >= 2:
                        stream.live = False
                        stream.room = None
                        stream.probe.offline_checks = reconnect_checks
                        stream.probe.confirmed_offline = True
                        stream.probe.due = time.monotonic() + 60
                        return "offline"
                    await sleep_or_stop(stream.stop, min(10, max(0, deadline - time.monotonic())))
            if not stream.enabled:
                return "paused"
            return "waiting_storage" if stream.stopped_for_storage else "unknown"
        finally:
            if part.is_dir():
                await self.finalize(stream, session_id, part)

    async def capture(self, stream):
        owner = f"{self.identity}-{uuid.uuid4().hex[:12]}"
        lost = asyncio.Event()
        renewal = None
        try:
            if stream.waiting_for_slot:
                stream.waiting_for_slot = False
                signal, room = await self.discover(stream)
                stream.probe.observe(signal, time.monotonic())
                if signal != "live" or stream.stop.is_set():
                    if stream.enabled and not stream.removed:
                        if signal == "offline" and stream.probe.confirmed_offline:
                            stream.live = False
                            stream.room = None
                            await self.status(stream, "offline")
                        elif signal == "unavailable":
                            await self.status(stream, "unknown")
                        else:
                            await self.status(stream, "live")
                    return
                if stream.room != room:
                    stream.first_live_at = time.monotonic()
                    stream.room = room
            start = time.monotonic()
            claimed = await self.db.rpc(
                "claim_stream", p_username=stream.username, p_owner=owner, p_ttl_seconds=LEASE_SECONDS,
            )
            if not claimed or stream.stop.is_set():
                if claimed:
                    await self.db.rpc("release_stream", p_username=stream.username, p_owner=owner)
                stream.probe.due = time.monotonic() + 10
                return
            renewal = asyncio.create_task(self.renew(stream, owner, start + LEASE_SECONDS - 1, lost))
            status = await self.capture_session(stream, owner)
            if stream.stopped_for_storage and stream.enabled and status != "offline":
                status = "waiting_storage"
            if not lost.is_set() and not stream.removed:
                await self.status(stream, status, owner)
            if status in ("live", "waiting_storage"):
                stream.waiting_since = time.monotonic()
                if status == "waiting_storage":
                    stream.probe.due = time.monotonic() + 10
            elif status != "offline":
                stream.probe.due = time.monotonic() + 10
        except Exception as error:
            LOG.error("@%s capture ended unexpectedly (%s)", stream.username, type(error).__name__)
            stream.probe.due = time.monotonic() + 10
        finally:
            stream.stop.set()
            if renewal:
                await renewal
                with contextlib.suppress(aiohttp.ClientError, asyncio.TimeoutError):
                    await self.db.rpc("release_stream", p_username=stream.username, p_owner=owner)
            stream.capture = None
            self.wake.set()

    async def jobs(self):
        try:
            for key, (job, outcome) in list(self.completed.items()):
                await self.db.complete_probe_job(job, outcome)
                self.completed.pop(key, None)
            outstanding = sum(stream.job is not None for stream in self.users.values())
            for _ in range(max(0, 16 - outstanding)):
                rows = await self.db.rpc(
                    "claim_job", p_kind="probe", p_owner=f"{self.identity}-{uuid.uuid4().hex[:12]}", p_ttl_seconds=120,
                    p_usernames=sorted(self.allowlist) if self.mode == "canary" else None,
                )
                if not rows:
                    return
                job = rows[0]
                stream = self.users.get(job["username"])
                if stream and stream.enabled and stream.desired_status != "recording" and job.get("attempts") == 1:
                    try:
                        enqueued = datetime.fromisoformat(str(job.get("enqueued_at", "")).replace("Z", "+00:00"))
                        if enqueued.tzinfo is not None:
                            stream.add_requested_at = enqueued
                    except ValueError:
                        pass
                if stream is None:
                    self.completed[job["job_key"]] = (job, "unavailable")
                elif not stream.enabled or stream.capture is not None:
                    self.completed[job["job_key"]] = (job, "observed")
                else:
                    stream.job = job
                    stream.probe.due = 0
                    stream.priority = time.monotonic()
                    self.wake.set()
        except (aiohttp.ClientError, asyncio.TimeoutError) as error:
            LOG.warning("Probe job queue temporarily unavailable (%s)", type(error).__name__)

    async def retry_parts(self, present):
        for part in list(self.pending_parts):
            try:
                await asyncio.to_thread(
                    recover_part, self.spool, part, eligible=self.eligible, present=present,
                )
            except (OSError, RuntimeError, ValueError, ImportError, subprocess.TimeoutExpired) as error:
                LOG.error("Retained a local part after retry (%s)", type(error).__name__)
            else:
                self.pending_parts.discard(part)
        await asyncio.to_thread(remove_empty_parts, self.spool)

    def apply_preferences(self, preferences):
        self.preferences = preferences
        for username, stream in list(self.users.items()):
            if username not in preferences:
                stream.enabled = False
                stream.removed = True
                stream.stop.set()
                if stream.observation is None and stream.capture is None:
                    if stream.job:
                        self.completed[stream.job["job_key"]] = (stream.job, "unavailable")
                    self.users.pop(username)
        for username, enabled in preferences.items():
            if not self.eligible(username):
                continue
            stream = self.users.get(username)
            if stream is None:
                self.users[username] = Stream(username, enabled, priority=time.monotonic())
            elif stream.enabled != enabled or stream.removed:
                stream.removed = False
                stream.enabled = enabled
                stream.probe = ProbeSchedule()
                stream.waiting_since = None
                stream.waiting_for_slot = False
                stream.priority = time.monotonic()
                if not enabled:
                    stream.stop.set()

    async def check_storage(self, now):
        if now >= self.disk_sample_due:
            self.disk_sample_due = now + DISK_SAMPLE_SECONDS
            try:
                sample = await asyncio.to_thread(
                    lambda: self.disk_pressure.sample(spool_reserve_bytes(self.spool)),
                )
            except OSError as error:
                LOG.warning("Capture storage check failed (%s)", type(error).__name__)
                self.disk_sample = None
                return True
            previous = self.disk_sample
            if previous is None or (sample.blocked, sample.critical) != (previous.blocked, previous.critical):
                LOG.info(
                    "capture_storage used_percent=%.2f free_bytes=%d blocked=%s critical=%s",
                    sample.used_percent, sample.free_bytes, sample.blocked, sample.critical,
                )
            self.disk_sample = sample
            if not sample.critical:
                self.free_at_last_storage_stop = None
            elif now >= self.next_storage_stop and (
                self.free_at_last_storage_stop is None or sample.free_bytes < self.free_at_last_storage_stop
            ) and (self.storage_draining is None or self.storage_draining.capture is None):
                candidates = [stream for stream in self.users.values() if stream.capture is not None and not stream.stop.is_set()]
                if candidates:
                    newest = max(candidates, key=lambda stream: stream.capture_started_at)
                    newest.stopped_for_storage = True
                    newest.stop.set()
                    self.storage_draining = newest
                    self.next_storage_stop = now + DISK_SHED_COOLDOWN_SECONDS
                    self.free_at_last_storage_stop = sample.free_bytes
                    LOG.warning("capture_storage_stop username=%s free_bytes=%d", newest.username, sample.free_bytes)
        return self.disk_sample is None or self.disk_sample.blocked or self.disk_sample.critical

    async def dispatch(self):
        now = time.monotonic()
        available_probes = 12 - sum(bool(stream.observation) for stream in self.users.values())
        due = sorted(
            (
                stream for stream in self.users.values() if stream.observation is None and stream.capture is None
                and not stream.removed and stream.probe.due <= now and (stream.enabled or stream.status != "paused")
            ),
            key=lambda stream: (stream.job is None, stream.probe.due, -stream.priority),
        )
        for stream in due[:max(0, available_probes)]:
            stream.observation = asyncio.create_task(self.observe(stream))
        if self.mode == "shadow":
            return
        storage_blocked = await self.check_storage(now)
        active = sum(bool(stream.capture) for stream in self.users.values())
        slots = 0 if storage_blocked else self.max_streams - active
        waiting = sorted(
            (
                stream for stream in self.users.values() if stream.waiting_since is not None
                and stream.capture is None and stream.observation is None and stream.enabled
            ), key=lambda stream: stream.waiting_since,
        )
        for stream in waiting[:slots]:
            stream.waiting_since = None
            stream.stop = asyncio.Event()
            stream.stopped_for_storage = False
            stream.capture_started_at = time.monotonic()
            stream.capture = asyncio.create_task(self.capture(stream))
        queued = waiting[slots:]
        for stream in queued:
            stream.waiting_for_slot = True
            stream.add_requested_at = None
        counts = (active + min(slots, len(waiting)), 0 if storage_blocked else len(queued), len(queued) if storage_blocked else 0)
        if counts != self.queue_counts:
            LOG.info("capture_capacity used=%d max=%d waiting=%d waiting_storage=%d", counts[0], self.max_streams, *counts[1:])
            self.queue_counts = counts
        wait_status = "waiting_storage" if storage_blocked else "waiting_slot"
        await asyncio.gather(*(self.status(stream, wait_status) for stream in queued))

    def request_refresh(self, kind="preferences"):
        if kind == "preferences":
            self.refresh_requested = True
        elif kind == "jobs":
            self.jobs_requested = True
        self.wake.set()

    def set_realtime_healthy(self, healthy):
        if self.realtime_healthy != healthy:
            self.realtime_healthy = healthy
            self.request_refresh("preferences")
            self.request_refresh("jobs")

    async def run(self):
        realtime = asyncio.create_task(self.db.changes(
            lambda: self.preferences, self.request_refresh, self.set_realtime_healthy,
        ))
        job_task = None
        retry_task = None
        initialized = False
        retry_due = 0
        refresh_due = 0
        jobs_due = 0
        try:
            while not self.stopping.is_set():
                self.wake.clear()
                should_refresh = self.refresh_requested or time.monotonic() >= refresh_due
                if should_refresh:
                    self.refresh_requested = False
                    interval = HEALTHY_PREFERENCES_SECONDS if self.realtime_healthy else FALLBACK_POLL_SECONDS
                    refresh_due = time.monotonic() + interval
                    try:
                        self.apply_preferences(await self.db.preferences())
                        if not initialized:
                            if self.mode != "shadow":
                                self.pending_parts.update(await asyncio.to_thread(
                                    recover_parts, self.spool, self.eligible, set(self.preferences),
                                ))
                            initialized = True
                    except (aiohttp.ClientError, asyncio.TimeoutError, OSError, RuntimeError, ValueError, ImportError, subprocess.TimeoutExpired) as error:
                        LOG.warning("Worker refresh delayed (%s)", type(error).__name__)
                if initialized:
                    await self.dispatch()
                    if self.mode != "shadow":
                        if (self.jobs_requested or time.monotonic() >= jobs_due) and (job_task is None or job_task.done()):
                            if job_task is not None:
                                job_task.result()
                            self.jobs_requested = False
                            interval = HEALTHY_CLAIM_SECONDS if self.realtime_healthy else FALLBACK_POLL_SECONDS
                            jobs_due = time.monotonic() + interval
                            job_task = asyncio.create_task(self.jobs())
                        if time.monotonic() >= retry_due and (retry_task is None or retry_task.done()):
                            if retry_task is not None:
                                retry_task.result()
                            retry_task = asyncio.create_task(self.retry_parts(set(self.preferences)))
                            retry_due = time.monotonic() + 30
                deadline = min(refresh_due, time.monotonic() + SCHEDULER_SECONDS)
                if initialized and self.mode != "shadow" and (job_task is None or job_task.done()):
                    deadline = min(deadline, jobs_due)
                await sleep_or_stop(self.wake, max(0, deadline - time.monotonic()))
        finally:
            realtime.cancel()
            await asyncio.gather(realtime, return_exceptions=True)
            tasks = [task for task in (job_task, retry_task) if task is not None]
            for stream in self.users.values():
                stream.stop.set()
                if stream.observation is not None:
                    stream.observation.cancel()
                    tasks.append(stream.observation)
                if stream.capture is not None:
                    tasks.append(stream.capture)
            await asyncio.gather(*tasks, return_exceptions=True)


async def sleep_or_stop(event, seconds):
    try:
        await asyncio.wait_for(event.wait(), seconds)
    except asyncio.TimeoutError:
        pass
    return event.is_set()


async def run(args, allowlist, url, key):
    timeout = aiohttp.ClientTimeout(total=8)
    realtime_jwt = (os.getenv("SUPABASE_REALTIME_JWT") or "").strip() or None
    if key.startswith("sb_secret_") and not realtime_jwt:
        LOG.warning("SUPABASE_SERVICE_ROLE_KEY is an sb_secret_ key and SUPABASE_REALTIME_JWT is unset: "
                    "Realtime CDC will fall back to 2s polling. Set SUPABASE_REALTIME_JWT to the legacy "
                    "service_role JWT to keep the 10s/60s cadence.")
    async with aiohttp.ClientSession(timeout=timeout) as session:
        worker = Worker(Database(session, url, key, realtime_jwt), args.spool, args.mode, allowlist, args.max_streams)

        def stop(*_):
            worker.stopping.set()
            worker.wake.set()

        for sig in (signal.SIGINT, signal.SIGTERM):
            signal.signal(sig, stop)
        LOG.info("Worker mode=%s slots=%d spool=%s", args.mode, args.max_streams, args.spool)
        await worker.run()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("shadow", "canary", "active"), default=os.getenv("RECORD_WORKER_MODE", "shadow"))
    parser.add_argument("--spool", type=Path, required=True, help="Persistent, local capture and publish spool")
    parser.add_argument("--max-streams", type=int, default=4)
    args = parser.parse_args()
    allowlist = {item.strip().lstrip("@").lower() for item in os.getenv("RECORD_WORKER_CANARY", "").split(",") if item.strip()}
    if args.mode not in ("shadow", "canary", "active"):
        parser.error("RECORD_WORKER_MODE must be shadow, canary or active")
    if args.mode == "canary" and (not allowlist or any(not valid_username(user) for user in allowlist)):
        parser.error("Canary requires a comma-separated RECORD_WORKER_CANARY allowlist")
    if args.max_streams < 1:
        parser.error("--max-streams must be positive")
    key = os.getenv("SUPABASE_SERVICE_ROLE_KEY")
    if not key:
        parser.error("SUPABASE_SERVICE_ROLE_KEY is required")
    url = os.getenv("SUPABASE_URL", constants.SUPABASE_URL).rstrip("/")
    args.spool = args.spool.resolve()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    with spool_lock(args.spool):
        asyncio.run(run(args, allowlist, url, key))


if __name__ == "__main__":
    main()
