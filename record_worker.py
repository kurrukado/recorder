@dataclasses.dataclass
class ProbeSchedule:
    due: float = 0
    offline_checks: int = 0
    confirmed_offline: bool = False

    def observe(self, signal, now):
        if signal == "offline":
            self.offline_checks += 1
            self.confirmed_offline |= self.offline_checks >= 2
            interval = 60 if self.confirmed_offline else 10
        elif signal == "live":
            self.offline_checks = 0
            self.confirmed_offline = False
            interval = 10
        else:
            self.offline_checks = 0
            interval = 20
        self.due = now + interval
        return self.due


def valid_username(username):
    return isinstance(username, str) and username not in (".", "..") and USERNAME.fullmatch(username) is not None


def ordered_sources(sources):
    if not isinstance(sources, list):
        return []
    urls = {}
    for url in sources:
        if not isinstance(url, str):
            continue
        try:
            parsed = urlsplit(url)
        except ValueError:
            continue
        if parsed.scheme in ("http", "https") and parsed.hostname:
            urls[url] = bool(FULL_HD.search(parsed.path))
    return sorted(urls, key=lambda url: not urls[url])


def write_json(path, data):
    temp = path.with_suffix(path.suffix + ".tmp")
    with temp.open("w", encoding="utf-8") as handle:
        json.dump(data, handle)
        handle.flush()
        os.fsync(handle.fileno())
    temp.replace(path)


def sync_media(paths):
    for path in paths:
        with path.open("rb" if os.name != "nt" else "r+b") as handle:
            os.fsync(handle.fileno())


def discard_attempt(path):
    if path.is_symlink():
        return
    # These paths are generated by this worker and hold one FFmpeg attempt.
    for child in path.iterdir():
        if child.is_file():
            child.unlink(missing_ok=True)
    with contextlib.suppress(OSError):
        path.rmdir()


def part_segments(part):
    result = []
    for attempt in sorted(part.iterdir()):
        if not attempt.is_dir() or attempt.is_symlink():
            continue
        if not (attempt / "selected.json").exists():
            continue
        result.extend(path for path in sorted(attempt.glob("*.ts")) if path.stat().st_size >= 188)
    return result


class MediaProcess:
    def __init__(self, process, path, url):
        self.process = process
        self.path = path
        self.url = url
        self.frame = 0
        self.resolution = (0, 0)
        self.media_seconds = 0.0
        self.last_progress = time.monotonic()
        self.first_frame_at = None
        self.synced = 0
        self.readers = [asyncio.create_task(self.read_progress()), asyncio.create_task(self.read_resolution())]

    @classmethod
    async def start(cls, url, path, duration):
        path.mkdir()
        network_options = []
        if url.startswith(("http://", "https://")):
            network_options = [
                "-rw_timeout", "8000000", "-user_agent",
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/136.0 Safari/537.36",
                "-referer", "https://www.tiktok.com/",
            ]
        process = await asyncio.create_subprocess_exec(
            recorder_core.FFMPEG_PATH, "-hide_banner", "-loglevel", "info", "-nostats",
            "-stats_period", "0.25", "-progress", "pipe:1",
            *network_options, "-analyzeduration", "1200000", "-probesize", "1048576",
            "-t", f"{duration:.3f}", "-i", url, "-map", "0:v:0", "-map", "0:a:0?", "-c", "copy",
            "-flush_packets", "1", "-f", "segment", "-segment_time", str(SEGMENT_SECONDS),
            "-segment_format", "mpegts", "-reset_timestamps", "1",
            "-segment_list", str(path / "segments.csv"), "-segment_list_type", "csv", str(path / "%05d.ts"),
            stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE,
        )
        try:
            write_json(path / "pid.json", {"pid": process.pid})
            return cls(process, path, url)
        except OSError:
            process.kill()
            await process.communicate()
            raise

    async def read_progress(self):
        async for line in self.process.stdout:
            name, _, value = line.partition(b"=")
            try:
                if name == b"frame":
                    frame = int(value)
                    if frame > self.frame:
                        self.frame = frame
                        self.last_progress = time.monotonic()
                        if self.first_frame_at is None:
                            self.first_frame_at = self.last_progress
                elif name == b"out_time_us":
                    self.media_seconds = max(self.media_seconds, int(value) / 1_000_000)
            except ValueError:
                continue

    async def read_resolution(self):
        async for line in self.process.stderr:
            if b"Stream #0:" in line and b"Video:" in line:
                match = RESOLUTION.search(line.split(b"Video:", 1)[1])
                if match and self.resolution == (0, 0):
                    self.resolution = tuple(int(dimension) for dimension in match.groups())

    def presentation_seconds(self):
        list_path = self.path / "segments.csv"
        try:
            rows = list_path.read_text(encoding="utf-8").splitlines()
            end = float(rows[-1].rsplit(",", 1)[-1])
        except (OSError, IndexError, ValueError):
            return self.media_seconds
        return max(self.media_seconds, end) if math.isfinite(end) else self.media_seconds

    def sync_closed_segments(self):
        closed = sorted(self.path.glob("*.ts"))[:-1]
        sync_media(closed[self.synced:])
        self.synced = len(closed)

    async def wait(self):
        await self.process.wait()
        await asyncio.gather(*self.readers)
        (self.path / "pid.json").unlink(missing_ok=True)

    async def close(self):
        if self.process.returncode is None:
            try:
                self.process.stdin.write(b"q\n")
                await self.process.stdin.drain()
                await asyncio.wait_for(self.process.wait(), 1)
            except (BrokenPipeError, ConnectionResetError, asyncio.TimeoutError):
                if self.process.returncode is None:
                    with contextlib.suppress(ProcessLookupError):
                        self.process.kill()
                    write_json(self.path / "interrupted.json", {"interrupted": True})
        await self.wait()


async def begin_capture(sources, part, *, duration, stop, startup_deadline=None):
    """Race a few source alternatives and keep their original video packets."""
    if not sources:
        return None
    if not part.exists():
        part.mkdir(parents=True)
        write_json(part / "part.json", {"started_at": datetime.now(timezone.utc).isoformat()})
    previous = [int(path.name.split("_", 1)[0]) for path in part.iterdir() if path.is_dir()]
    batch_start = max(previous, default=-1) + 1
    for offset in range(0, len(sources), 3):
        deadline = time.monotonic() + 10
        if startup_deadline is not None:
            deadline = min(deadline, startup_deadline)
        if stop.is_set() or deadline <= time.monotonic():
            break
        choices = []
        winner = None
        selected = False
        try:
            for index, url in enumerate(sources[offset:offset + 3]):
                path = part / f"{batch_start + offset:05d}_{index}"
                choices.append(await MediaProcess.start(url, path, duration))
            while not stop.is_set() and time.monotonic() < deadline:
                ready = [choice for choice in choices if choice.first_frame_at is not None]
                all_done = all(choice.process.returncode is not None for choice in choices)
                if ready:
                    full_hd = [choice for choice in ready if min(choice.resolution) >= 1080]
                    first = min(ready, key=lambda choice: choice.first_frame_at)
                    all_answered = all(choice in ready or all(reader.done() for reader in choice.readers) for choice in choices)
                    if full_hd or all_answered:
                        winner = (full_hd or [first])[0]
                        break
                if all_done and not ready:
                    await asyncio.gather(*(choice.wait() for choice in choices))
                    if not any(choice.frame for choice in choices):
                        break
                await asyncio.sleep(0.1)
            if winner is None and not stop.is_set():
                winner = next((choice for choice in choices if choice.frame), None)
            if winner is not None:
                write_json(winner.path / "selected.json", {"selected": True})
                selected = True
                return winner
        finally:
            rejected = [choice for choice in choices if not selected or choice is not winner]
            await asyncio.gather(*(choice.close() for choice in rejected))
            for choice in rejected:
                discard_attempt(choice.path)
    return None


def recover_process(attempt):
    """Stop a surviving FFmpeg writer before handing its files to the publisher."""
    marker = attempt / "pid.json"
    if not marker.is_file():
        return
    import psutil
    try:
        data = json.loads(marker.read_text(encoding="utf-8"))
        process = psutil.Process(data["pid"])
        if process.name().lower().startswith("ffmpeg") and str(attempt / "%05d.ts") in process.cmdline():
            process.terminate()
            try:
                process.wait(timeout=2)
            except psutil.TimeoutExpired:
                process.kill()
                process.wait(timeout=2)
    except (psutil.NoSuchProcess, json.JSONDecodeError, ValueError, KeyError):
        pass
    write_json(attempt / "interrupted.json", {"interrupted": True})
    marker.unlink(missing_ok=True)


def quarantine_incomplete_tail(attempt):
    marker = attempt / "interrupted.json"
    if not marker.exists():
        return
    for tail in sorted(attempt.glob("*.ts"), reverse=True):
        probe = subprocess.run(
            [
                "ffprobe", "-v", "error", "-select_streams", "v:0",
                "-show_entries", "stream=width,height:format=duration", "-of", "json", str(tail),
            ],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=12, check=False,
        )
        try:
            data = json.loads(probe.stdout)
            duration = float(data["format"]["duration"])
            video = next(iter(data.get("streams", [])), {})
            if probe.returncode == 0 and math.isfinite(duration) and duration > 0 and video.get("width", 0) > 0:
                break
        except (KeyError, TypeError, ValueError):
            pass
        tail.replace(tail.with_suffix(".ts.incomplete"))
        LOG.warning("Retained an incomplete local capture fragment under %s", attempt)
    marker.unlink(missing_ok=True)


def session_started_at(session_id):
    started = datetime.strptime(session_id.split("_", 1)[0], "%Y%m%dT%H%M%SZ")
    return started.replace(tzinfo=timezone.utc).isoformat()


def enqueue_part(spool, username, session_id, part, *, deleted=False):
    if (part / "queued.json").exists():
        return
    if deleted:
        for attempt in part.iterdir():
            if attempt.is_dir():
                discard_attempt(attempt)
        return
    for attempt in part.iterdir():
        if attempt.is_dir() and not attempt.is_symlink() and (attempt / "selected.json").exists():
            quarantine_incomplete_tail(attempt)
    segments = part_segments(part)
    if not segments:
        return
    from record_worker_media import enqueue_recording

    metadata = part / "part.json"
    details = json.loads(metadata.read_text(encoding="utf-8")) if metadata.exists() else {}
    started_at = details.get("started_at") or session_started_at(session_id)
    last_write = max(path.stat().st_mtime for path in segments)
    capture_ended_at = details.get("capture_ended_at") or datetime.fromtimestamp(last_write, timezone.utc).isoformat()
    reconnect_indexes = [
        index for index in range(1, len(segments)) if segments[index - 1].parent != segments[index].parent
    ]
    sync_media(segments)
    enqueue_recording(
        spool, username=username, session_id=session_id, part_number=int(part.name), segments=segments,
        started_at=started_at, capture_ended_at=capture_ended_at, reconnect_indexes=reconnect_indexes,
    )
    write_json(part / "queued.json", {"queued": True})


def capture_parts(spool):
    for part in sorted((spool / "capture").glob("*/*/[0-9][0-9][0-9][0-9]")):
        if part.is_dir() and not any(path.is_symlink() for path in (part, part.parent, part.parent.parent)):
            yield part


def recover_part(spool, part, *, eligible, present):
    session_id = part.parent.name
    username = part.parent.parent.name
    if not valid_username(username):
        return
    attempts = sorted(path for path in part.iterdir() if path.is_dir() and not path.is_symlink())
    for attempt in attempts:
        recover_process(attempt)
    if not eligible(username):
        return
    # A crash between the first frame and the selection marker can leave several
    # candidate files. Keep just one attempt from each startup race.
    groups = {}
    for attempt in attempts:
        groups.setdefault(attempt.name.split("_", 1)[0], []).append(attempt)
    for group in groups.values():
        candidate = next((path for path in group if (path / "selected.json").exists()), None)
        if candidate is None:
            candidate = max(group, key=lambda path: sum(file.stat().st_size for file in path.glob("*.ts")))
            if any(candidate.glob("*.ts")):
                write_json(candidate / "selected.json", {"recovered": True})
        for rejected in group:
            if rejected != candidate:
                discard_attempt(rejected)
    enqueue_part(spool, username, session_id, part, deleted=username not in present)


def recover_parts(spool, eligible, present):
    pending = set()
    for part in capture_parts(spool):
        try:
            recover_part(spool, part, eligible=eligible, present=present)
        except (OSError, RuntimeError, ValueError, ImportError, subprocess.TimeoutExpired) as error:
            LOG.error("Retained a local part after recovery failure (%s)", type(error).__name__)
            pending.add(part)
    return pending


def remove_empty_parts(spool):
    for part in capture_parts(spool):
        if (part / "queued.json").exists() and not any(path for path in part.glob("*/*") if path.name.endswith((".ts", ".ts.incomplete"))):
            for attempt in part.iterdir():
                if attempt.is_dir():
                    discard_attempt(attempt)
            discard_attempt(part)
            for parent in (part.parent, part.parent.parent):
                with contextlib.suppress(OSError):
                    parent.rmdir()


@contextlib.contextmanager
def spool_lock(spool):
    spool.mkdir(parents=True, exist_ok=True)
    with (spool / "capture.lock").open("a+b") as handle:
        if os.name == "nt":
            import msvcrt
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield


class Database:
    def __init__(self, session, url, key, realtime_jwt=None):
        self.session = session
        self.url = url
        self.key = key
        # sb_secret_ keys are not JWTs: Realtime would fall back to the anon role and be
        # denied on record_worker_jobs (RLS without policies), silently dropping CDC.
        self.jwt = realtime_jwt or (None if key.startswith("sb_secret_") else key)
        self.headers = {"apikey": key}
        if self.jwt:
            self.headers["Authorization"] = f"Bearer {self.jwt}"

    async def request(self, method, path, **options):
        async with self.session.request(method, f"{self.url}/rest/v1/{path}", headers=self.headers, **options) as response:
            response.raise_for_status()
            if response.status != 204 and response.content_length != 0:
                return await response.json()

    async def rpc(self, function, **args):
        return await self.request("POST", f"rpc/record_worker_{function}", json=args)

    async def preferences(self):
        preferences = {}
        for offset in range(0, 1000000, 1000):
            rows = await self.request("GET", "tiktok_streamers", params={
                "select": "username,recording_enabled",
                "order": "username",
                "limit": "1000",
                "offset": str(offset),
            })
            for row in rows:
                if valid_username(row["username"]) and isinstance(row["recording_enabled"], bool):
                    preferences[row["username"]] = row["recording_enabled"]
            if len(rows) < 1000:
                return preferences
        raise RuntimeError("Streamer preference pagination did not finish")

    async def complete_probe_job(self, job, state):
        attempts = job["attempts"]
        unavailable = state == "unavailable"
        retry = unavailable and attempts < 3
        now = datetime.now(timezone.utc)
        available = now + timedelta(seconds=20 if retry else 0)
        await self.request("PATCH", "record_worker_jobs", params={
            "job_key": f"eq.{job['job_key']}",
            "lease_owner": f"eq.{job['lease_owner']}",
            "status": "eq.running",
        }, json={
            "status": "queued" if retry else "failed" if unavailable else "ready",
            "lease_owner": None,
            "lease_until": None,
            "available_at": available.isoformat(),
            "updated_at": now.isoformat(),
            "last_error": "TikTok discovery temporarily unavailable" if unavailable else None,
        })

    async def changes(self, preferences, notify, connectivity):
        ws_url = self.url.replace("https://", "wss://", 1).replace("http://", "ws://", 1)
        while True:
            connected = False
            try:
                async with self.session.ws_connect(
                    f"{ws_url}/realtime/v1/websocket",
                    params={"apikey": self.key, "vsn": "1.0.0"}, heartbeat=20,
                ) as ws:
                    topic = "realtime:record-worker"
                    subscriptions = [
                        {"event": "*", "schema": "public", "table": "tiktok_streamers"},
                        {"event": "*", "schema": "public", "table": "record_worker_jobs", "filter": "kind=eq.probe"},
                    ]
                    required_tables = {item["table"] for item in subscriptions}
                    payload = {"config": {"postgres_changes": subscriptions}}
                    if self.jwt:
                        payload["access_token"] = self.jwt
                    await ws.send_json({
                        "topic": topic, "event": "phx_join",
                        "payload": payload,
                        "ref": "1", "join_ref": "1",
                    })
                    ref = 1
                    registered = False
                    postgres_ready = False
                    ack_due = time.monotonic() + REALTIME_JOIN_SECONDS
                    heartbeat_due = time.monotonic() + REALTIME_HEARTBEAT_SECONDS
                    while not ws.closed:
                        now = time.monotonic()
                        if now >= ack_due:
                            break
                        if now >= heartbeat_due:
                            ref += 1
                            await ws.send_json({"topic": "phoenix", "event": "heartbeat", "payload": {}, "ref": str(ref)})
                            ack_due = now + REALTIME_ACK_SECONDS
                            heartbeat_due = now + REALTIME_HEARTBEAT_SECONDS
                            continue
                        try:
                            message = await asyncio.wait_for(ws.receive_json(), min(ack_due, heartbeat_due) - now)
                        except asyncio.TimeoutError:
                            continue
                        event = message.get("event")
                        channel = message.get("topic")
                        payload = message.get("payload", {})
                        if event in ("phx_error", "phx_close") and channel == topic:
                            break
                        if event == "system" and channel == topic and payload.get("extension") == "postgres_changes":
                            if payload.get("status") != "ok":
                                break
                            postgres_ready = True
                        if event == "phx_reply" and message.get("ref") == str(ref):
                            if (ref == 1 and channel != topic) or (ref != 1 and channel != "phoenix"):
                                continue
                            if payload.get("status") != "ok":
                                break
                            if ref == 1:
                                accepted = payload.get("response", {}).get("postgres_changes", [])
                                if not required_tables.issubset(item.get("table") for item in accepted):
                                    break
                                registered = True
                            else:
                                ack_due = math.inf
                        # Joining the Phoenix channel alone does not prove CDC is active.
                        if not connected and registered and postgres_ready:
                            connected = True
                            ack_due = math.inf
                            connectivity(True)
                        if not connected or event != "postgres_changes" or channel != topic:
                            continue
                        self.notify_change(message, preferences, notify)
            except Exception as error:
                LOG.debug("Realtime disconnected (%s); polling preferences", type(error).__name__)
            finally:
                if connected:
                    connectivity(False)
            await asyncio.sleep(5)

    @staticmethod
    def notify_change(message, preferences, notify):
        data = message.get("payload", {}).get("data", {})
        record = data.get("record") or {}
        table = data.get("table")
        username = record.get("username")
        if table == "record_worker_jobs" and record.get("kind") == "probe" and record.get("status") == "queued":
            if username not in preferences():
                notify("preferences")
            notify("jobs")
        elif table == "tiktok_streamers":
            if data.get("type") == "DELETE" or preferences().get(username) != record.get("recording_enabled"):
                notify("preferences")


